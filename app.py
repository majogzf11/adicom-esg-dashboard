        task_id = int(row["ID_Tarea"])
        key = f"{cert}_{task_id}"
        st.checkbox(
            row["Requisito_Documental"],
            value=st.session_state["checklist_state"].get(str(task_id), False),
            key=f"chk_{key}",
            on_change=on_task_toggle,
            args=(key, task_id),
        )


